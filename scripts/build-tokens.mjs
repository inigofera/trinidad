import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, '..');

const tokensJsonPath = resolve(rootDir, 'src/lib/tokens/tokens.json');
const tokensCssPath = resolve(rootDir, 'src/lib/tokens/tokens.css');
const tokensTsPath = resolve(rootDir, 'src/lib/tokens/tokens.ts');

const tokensRaw = readFileSync(tokensJsonPath, 'utf-8');
const tokens = JSON.parse(tokensRaw);

function getByPath(obj, pathStr) {
  const parts = pathStr.split('.');
  let current = obj;
  for (const part of parts) {
    if (!current || typeof current !== 'object') return undefined;
    current = current[part];
  }
  return current;
}

function resolveAliasValue(val) {
  if (typeof val === 'string') {
    const match = val.match(/^\{([^}]+)\}$/);
    if (match) {
      const target = getByPath(tokens, match[1]);
      if (target && target.$value !== undefined) {
        return resolveAliasValue(target.$value);
      }
    }
  }
  return val;
}

function resolveCssVar(val) {
  if (typeof val === 'string') {
    const match = val.match(/^\{([^}]+)\}$/);
    if (match) {
      const aliasPath = match[1];
      if (aliasPath.startsWith('primitive.color.')) {
        const colorName = aliasPath.replace('primitive.color.', '');
        return `var(--raw-${colorName})`;
      }
      if (aliasPath.startsWith('primitive.font.')) {
        const fontName = aliasPath.replace('primitive.font.', '');
        return `var(--font-${fontName})`;
      }
    }
  }
  return val;
}

// 1. Build CSS
const cssLines = [
  '/* Generated by scripts/build-tokens.mjs - DO NOT EDIT MANUALLY */',
  ':root {',
  '  /* Primitives: Color */'
];

for (const [name, token] of Object.entries(tokens.primitive.color)) {
  cssLines.push(`  --raw-${name}: ${token.$value};`);
}

cssLines.push('');
cssLines.push('  /* Primitives: Font */');
for (const [name, token] of Object.entries(tokens.primitive.font)) {
  cssLines.push(`  --font-${name}: ${token.$value};`);
}

if (tokens.primitive['font-weight']) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Font Weight */');
  for (const [name, token] of Object.entries(tokens.primitive['font-weight'])) {
    cssLines.push(`  --font-weight-${name}: ${token.$value};`);
  }
}

if (tokens.primitive['font-size']) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Font Size */');
  for (const [name, token] of Object.entries(tokens.primitive['font-size'])) {
    cssLines.push(`  --font-size-${name}: ${token.$value};`);
  }
}

if (tokens.primitive['line-height']) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Line Height */');
  for (const [name, token] of Object.entries(tokens.primitive['line-height'])) {
    cssLines.push(`  --leading-${name}: ${token.$value};`);
  }
}

if (tokens.primitive['aspect-ratio']) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Aspect Ratio */');
  for (const [name, token] of Object.entries(tokens.primitive['aspect-ratio'])) {
    cssLines.push(`  --aspect-${name}: ${token.$value};`);
  }
}

if (tokens.primitive.shadow) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Shadow */');
  for (const [name, token] of Object.entries(tokens.primitive.shadow)) {
    cssLines.push(`  --shadow-${name}: ${token.$value};`);
  }
}

if (tokens.primitive.spacing) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Spacing */');
  for (const [name, token] of Object.entries(tokens.primitive.spacing)) {
    cssLines.push(`  --spacing-${name}: ${token.$value};`);
  }
}

if (tokens.primitive.dimension) {
  cssLines.push('');
  cssLines.push('  /* Primitives: Dimension */');
  for (const [name, token] of Object.entries(tokens.primitive.dimension)) {
    cssLines.push(`  --${name}: ${token.$value};`);
  }
}

cssLines.push('}');
cssLines.push('');

// The first semantic theme in tokens.json is the default: it is emitted on :root
// so pages render correctly before any data-theme attribute exists (SSR/FOUC),
// and again scoped under its [data-theme] hook. Every later theme becomes a pure
// override block, which also enables nested ThemeScope subtrees.
const semanticThemes = Object.entries(tokens.semantic);
for (let index = 0; index < semanticThemes.length; index += 1) {
  const [themeName, themeTokens] = semanticThemes[index];
  const selector =
    index === 0 ? `:root, [data-theme="${themeName}"]` : `[data-theme="${themeName}"]`;
  cssLines.push(selector + ' {');
  cssLines.push(`  /* Semantic: ${themeName}${index === 0 ? ' (Default)' : ''} */`);
  for (const [name, token] of Object.entries(themeTokens)) {
    cssLines.push(`  --${name}: ${resolveCssVar(token.$value)};`);
  }
  cssLines.push('}');
  cssLines.push('');
}

cssLines.push(':root, [data-density="comfortable"] {');
cssLines.push('  /* Density: Comfortable (Default) */');
for (const [name, token] of Object.entries(tokens.density.comfortable)) {
  cssLines.push(`  --${name}: ${token.$value};`);
}
cssLines.push('}');
cssLines.push('');

cssLines.push('[data-density="compact"] {');
cssLines.push('  /* Density: Compact Override */');
for (const [name, token] of Object.entries(tokens.density.compact)) {
  cssLines.push(`  --${name}: ${token.$value};`);
}
cssLines.push('}');
cssLines.push('');

cssLines.push(
  '[data-motion="reduced"], [data-motion="reduced"] *, [data-motion="reduced"] *::before, [data-motion="reduced"] *::after {'
);
cssLines.push('  animation-duration: 0.01ms !important;');
cssLines.push('  animation-iteration-count: 1 !important;');
cssLines.push('  transition-duration: 0.01ms !important;');
cssLines.push('  scroll-behavior: auto !important;');
cssLines.push('}');
cssLines.push('');

// 2. Build TypeScript
function deepResolve(obj) {
  if (Array.isArray(obj)) {
    return obj.map(deepResolve);
  }
  if (obj && typeof obj === 'object') {
    if ('$value' in obj) {
      return resolveAliasValue(obj.$value);
    }
    const result = {};
    for (const [key, val] of Object.entries(obj)) {
      result[key] = deepResolve(val);
    }
    return result;
  }
  return resolveAliasValue(obj);
}

const resolvedTokens = deepResolve(tokens);
const rawTs = `// Generated by scripts/build-tokens.mjs - DO NOT EDIT MANUALLY
export const tokens = ${JSON.stringify(resolvedTokens, null, 2)} as const;

export type Tokens = typeof tokens;
`;

const prettierConfig = (await prettier.resolveConfig(tokensCssPath)) || {};

const formattedCss = await prettier.format(cssLines.join('\n'), {
  ...prettierConfig,
  parser: 'css'
});

const formattedTs = await prettier.format(rawTs, {
  ...prettierConfig,
  parser: 'typescript'
});

mkdirSync(dirname(tokensCssPath), { recursive: true });
writeFileSync(tokensCssPath, formattedCss, 'utf-8');
console.log(`✓ Generated ${tokensCssPath}`);

writeFileSync(tokensTsPath, formattedTs, 'utf-8');
console.log(`✓ Generated ${tokensTsPath}`);
